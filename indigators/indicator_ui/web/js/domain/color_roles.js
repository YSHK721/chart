// color_roles.js — 色の「意味」（ColorRole）語彙の台帳（基本設計_指標カラーテーマ.md §4.1.1）。
//
// 設計入力（§2.3）: 色の意味は既に存在する（Python 側の _COLOR_MA / _BULL_COLOR 等の命名＝E-3、
//   共有定数 EVQ_COLOR＝E-4）が、それを表現する**型が無い**。そのため意味は 25 個の Python
//   ファイル・front JS 50 リテラル・CSS 219 リテラルへ「値」として分散し、同一の意味に複数の色
//   （上 3 色・下 3 色＝E-24）、同一の色に複数の意味（緑/赤が 3 意味＝E-26）という状態になっている。
//   本モジュールはその「意味」を 1 つの閉集合として型に昇格させる単一情報源である。
//
// 語彙は**意味軸の単一閉集合**（§4.1.0）。2 軸（意味 × 部位）を採らないのは、トークン数が積に
//   なりテーマ編集 UI の行数が積になる＝目的 1（認知負荷の軽減）に正面から反するため。部位の
//   区別は色ではなく既存の別チャネル（線種 style / 線幅 width / 表示形式 display）が担う。
//
// OCP: 指標を何件追加してもこの台帳は増えない（新指標は SeriesDef へ既存トークンを宣言するだけ）。
//   クロム配線点を増やしても増えない（chrome_tokens.js の表へ 1 行足すだけ）。増えるのは「新しい
//   意味」が現れたときだけで、それは v2 の承認事項（§3.2 N-3 の profit/loss 等）に列挙済み。
//
// ライブ・リプレイ共有（replay 側は symlink 参照＝単一実体）。actor_driven_ids.js と同型の台帳。

// 表順は §4.1.1 の表（1..14）と一致させる。テーマ編集ダイアログの行順（§6.3）はこの順序を読む
//   （手書きの配列を UI 側に持たせない＝台帳へ足せば UI が追随する）。
//   1..9  … 指標側で使う意味（SeriesDef 単位に 1 つ宣言する）
//   1,2   … 指標側とクロム側で**共有**される（同一の意味には同一の色＝FR-C11 の実体）
//   10..14… クロム側で使う意味（chrome_tokens.js の配線点が束ねる）
export const COLOR_ROLES = Object.freeze([
  // --- 方向（指標・クロム共有）---
  'bullish',   // 強気・上方向: 価格が上へ向かう／支持されている
  'bearish',   // 弱気・下方向: 価格が下へ向かう／抵抗されている
  // --- 指標側の意味 ---
  'neutral',   // 基準・中立: 基準となる水準（回帰平均・0% 線・中心線）
  'alert',     // 警戒・外れ値: 通常域を外れた／過熱している
  'primary',   // 主出力: その指標の主たる出力値
  'secondary', // 副出力: 主出力に随伴する平滑線・シグナル線・副オシレータ
  'range',     // 通常域: 正常域の境界（分位バンド・BB 上下・確率帯）
  'level',     // 参照水準: 価格軸上の参照線（horizontal_line 経路の全系列）
  'muted',     // 非強調: チャート上で読ませない補助情報（読取欄専用系列）
  // --- クロム側の意味 ---
  'surface',   // 面: チャートの地（背景）。減光・分析 tint・リプレイ減光境界が従属する
  'grid',      // 目盛線: 面の上に引く最も控えめな構造線
  'border',    // 境界: 構造の境界（価格軸線・時間軸線・pane 区切り）
  'text',      // 文字: 軸ラベル等の読ませる文字
  'highlight', // 現在地: 「今この瞬間の値」を指す強調（値の上下と無関係に常時同色）
]);

// トークンの綴りを参照する名前付き定数（catalog.js / chrome_tokens.js が文字列リテラルを
//   持たないための単一情報源）。キーはトークンの大文字化で機械的に導く（手書きしない）。
export const ColorRole = Object.freeze(
  Object.fromEntries(COLOR_ROLES.map((t) => [t.toUpperCase(), t])),
);

// 語彙の集合（述語の O(1) 判定用・内部）。
const ROLE_SET = new Set(COLOR_ROLES);

// 値が語彙に属するトークンか。**全域的**（§7.3 LSP）: 未知値・非文字列・null/undefined でも
//   例外を投げず false を返す。§5.7 F-C3（未知トークンは未宣言として扱う）の判定源であり、
//   呼び出し側に型ガードの分岐を要求しない。
export function isColorRole(value) {
  return typeof value === 'string' && ROLE_SET.has(value);
}
