"""素材の版（内容の指紋）— 「持ち越した物は今の物と同じか」を答える**唯一の定義**。

なぜ 1 か所に置くか:
    epoch の中で不変な量を持ち越す仕組みは、素材（確定系列）・帯外イベント履歴・役割判定の
    中央値・§5.3.3 の比較集合と、複数の面に現れる（ISSUE-457 / ISSUE-464）。版の取り方を
    面ごとに手書きすると、片方だけ弱い版になったときに**その面だけが古い物を配り続ける**。
    出力はそれらしいままなので状態検証では落ちない（ISSUE-450 と同型）。

なぜ本数と端だけでは足りないか:
    確定した履歴の途中を遡って訂正する経路が実在する（ロールアップの再生成・読み取り時の
    外れ値補正の変更・供給の遡り訂正）。本数も端も変わらないため、端だけの版では 1 周期ぶん
    見落とす。**速いことより古い物を配らないことが優先する**（ISSUE-457 の裁定と同じ順序）。

費用:
    numpy の連続化 1 回とバイト列のハッシュ 1 回。持ち越しで消える計算（1 点ずつの Python
    ループ・周期始端のスカラ呼び出し）とは桁が違う。
"""
from __future__ import annotations

import numpy as np


def fingerprint_of(values) -> "tuple[int, int]":
    """数値列の版（要素数 ＋ 内容の指紋）。NaN を含んでも決定的である。

    `nan != nan` なので値そのものの比較で版を作ると常に版違いになる。バイト列は NaN でも
    同一表現なので、そのハッシュは「同じ物か」を素直に答える。

    `(時刻, 値)` の対の列をそのまま渡してよい（2 次元は平坦化して指紋を取る）。
    """
    array = np.ascontiguousarray(np.asarray(values, dtype=np.float64).ravel())
    return (int(array.size), hash(array.tobytes()))
